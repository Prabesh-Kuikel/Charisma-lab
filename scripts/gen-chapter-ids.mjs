// Regenerates server/content/chapter-ids.js from the real chapter maps.
// Run after adding chapters:  node scripts/gen-chapter-ids.mjs
// The audit fails if the generated list is stale, so this cannot silently drift.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const content = path.join(here, '..', 'server', 'content');

const SOURCES = [
  ['library-deep.js', 'LIBRARY_DEEP'],
  ['library-deep-2.js', 'LIBRARY_DEEP_2'],
  ['library-deep-3.js', 'LIBRARY_DEEP_3'],
  ['library-extra-deep.js', 'LIBRARY_EXTRA_DEEP'],
  ['library-extra-3-deep.js', 'LIBRARY_EXTRA_3_DEEP'],
];

const ids = [];
for (const [file, name] of SOURCES) {
  const mod = await import(path.join(content, file));
  ids.push(...Object.keys(mod[name] || {}));
}

const out = `// ─────────────────────────────────────────────────────────────
//  Chapter id manifest (generated by scripts/gen-chapter-ids.mjs)
//  Lets the app know WHICH entries have a long-form chapter without
//  shipping 243 KB of prose in the initial bundle. The audit fails if
//  this list drifts from the real chapter maps.
// ─────────────────────────────────────────────────────────────

export const CHAPTER_IDS = [
${ids.map((i) => `  '${i}',`).join('\n')}
];
`;
fs.writeFileSync(path.join(content, 'chapter-ids.js'), out);
console.log(`wrote ${ids.length} chapter ids`);
